//go:build ignore

// notices writes THIRD_PARTY_NOTICES.md: the license text of every third-party
// module compiled into zbxctl on any release platform, plus the Go license for
// the standard library. Run it with
//
//	go run scripts/notices/main.go > THIRD_PARTY_NOTICES.md
//
// CI regenerates it and fails if the committed file is out of date, so a new
// dependency cannot ship without its notice.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct{ path, version, dir string }

type extra struct{ name, text string }

func main() {
	seen := map[string]module{}
	for _, goos := range []string{"linux", "darwin", "windows"} {
		cmd := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}", "./cmd/zbxctl")
		cmd.Env = append(os.Environ(), "GOOS="+goos, "CGO_ENABLED=0")
		cmd.Stderr = os.Stderr
		out, err := cmd.Output()
		if err != nil {
			fmt.Fprintln(os.Stderr, "go list failed:", err)
			os.Exit(1)
		}
		for _, line := range strings.Split(string(out), "\n") {
			f := strings.Fields(line)
			if len(f) == 3 {
				seen[f[0]] = module{f[0], f[1], f[2]}
			}
		}
	}
	var mods []module
	for _, m := range seen {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].path < mods[j].path })

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	var b bytes.Buffer
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("zbxctl itself is released under the MIT License (see LICENSE). It is built with the\n")
	b.WriteString("third-party software below, each used under its own license. The license texts are\n")
	b.WriteString("reproduced as the projects publish them. This file is generated by\n")
	b.WriteString("`go run scripts/notices/main.go`; do not edit it by hand.\n\n")
	b.WriteString("| Component | Version | License |\n|---|---|---|\n")

	type entry struct {
		name, version, spdx, text string
		extras                    []extra // NOTICE and PATENTS files that ship with the license
	}
	var entries []entry
	std, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(goroot)), "LICENSE"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "cannot read the Go license:", err)
		os.Exit(1)
	}
	goEntry := entry{"Go standard library and runtime", "compiled in", "BSD-3-Clause", string(std), nil}
	if pat, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(goroot)), "PATENTS")); err == nil {
		goEntry.extras = append(goEntry.extras, extra{"PATENTS", string(pat)})
	}
	entries = append(entries, goEntry)
	for _, m := range mods {
		lic := ""
		var extras []extra
		ents, _ := os.ReadDir(m.dir)
		for _, e := range ents {
			up := strings.ToUpper(e.Name())
			data, _ := os.ReadFile(filepath.Join(m.dir, e.Name()))
			switch {
			case lic == "" && (strings.HasPrefix(up, "LICENSE") || strings.HasPrefix(up, "LICENCE") || strings.HasPrefix(up, "COPYING")):
				lic = string(data)
			case up == "NOTICE" || up == "PATENTS":
				extras = append(extras, extra{up, string(data)})
			}
		}
		if lic == "" {
			fmt.Fprintf(os.Stderr, "no license file found for %s\n", m.path)
			os.Exit(1)
		}
		entries = append(entries, entry{m.path, m.version, spdx(lic), lic, extras})
	}
	for _, e := range entries {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", e.name, e.version, e.spdx)
	}
	for _, e := range entries {
		fmt.Fprintf(&b, "\n---\n\n## %s %s\n\nLicense: %s\n\n```text\n%s\n```\n", e.name, e.version, e.spdx, strings.TrimSpace(e.text))
		for _, x := range e.extras {
			fmt.Fprintf(&b, "\n%s file of %s:\n\n```text\n%s\n```\n", x.name, e.name, strings.TrimSpace(x.text))
		}
	}
	os.Stdout.Write(b.Bytes())
}

// spdx names a license from its text. Anything it does not recognise is
// reported as UNKNOWN so a human looks at it.
func spdx(text string) string {
	var ids []string
	if strings.Contains(text, "Permission is hereby granted, free of charge") {
		ids = append(ids, "MIT")
	}
	if strings.Contains(text, "Apache License") && strings.Contains(text, "Version 2.0") {
		ids = append(ids, "Apache-2.0")
	}
	if strings.Contains(text, "Redistribution and use in source and binary forms") {
		if strings.Contains(text, "Neither the name") {
			ids = append(ids, "BSD-3-Clause")
		} else {
			ids = append(ids, "BSD-2-Clause")
		}
	}
	if len(ids) == 0 {
		return "UNKNOWN"
	}
	return strings.Join(ids, " AND ")
}
